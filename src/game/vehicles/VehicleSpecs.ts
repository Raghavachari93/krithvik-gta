export type VehicleClass = 'sedan' | 'sports' | 'super' | 'suv' | 'bike' | 'truck' | 'police' | 'taxi' | 'swat' | 'muscle' | 'van' | 'boat';

export interface BodyShape {
  gc: number; // ground clearance (bottom of body)
  belt: number; // belt line height
  nose: number; // nose height
  tail: number; // tail height
  cabRear: number; // x of rear window base (from centre, metres)
  cabFront: number; // x of windshield base
  roofRear: number;
  roofFront: number;
  roofH: number;
  wheelR: number;
  wheelX: number; // half wheelbase
  track: number; // half track
  spoiler?: boolean;
  boxy?: boolean;
}

export interface VehicleSpec {
  id: string;
  name: string;
  cls: VehicleClass;
  price: number;
  mass: number;
  maxSpeed: number; // m/s
  accel: number; // m/s^2 at low speed
  brake: number;
  reverse: number;
  steerMax: number;
  grip: number; // lateral m/s^2
  driftGrip: number; // handbrake multiplier
  len: number;
  wid: number;
  height: number;
  health: number;
  fuelCap: number;
  fuelUse: number; // litres / s at full throttle
  engineBase: number;
  engineType: 'sawtooth' | 'square' | 'triangle';
  colors: number[];
  shape: BodyShape;
  boat?: boolean;
  bike?: boolean;
  police?: boolean;
  gears: number;
  /** speed-sensitive steering: steering reduces above this speed */
  steerFalloff: number;
}

